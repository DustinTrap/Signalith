// Package agents generates Fluent Bit configurations so nobody has to write
// agent config by hand: pick the OS, copy the file, restart the agent.
package agents

import (
	"fmt"
	"net/url"
	"strings"
)

// Options select what an agent collects.
type Options struct {
	OS        string // "linux" or "windows"
	ServerURL string // Signalith public URL
	Token     string // ingest token
	// LinuxSource is "file" (tail /var/log/auth.log and /var/log/secure)
	// or "journal" (systemd journal, for distros without rsyslog).
	LinuxSource string
	// Sysmon adds the Sysmon operational channel on Windows.
	Sysmon bool
}

// Agent is a generated agent setup.
type Agent struct {
	OS         string   `json:"os"`
	ConfigPath string   `json:"config_path"`
	Config     string   `json:"config"`
	Steps      []string `json:"steps"`
}

// Generate returns a Fluent Bit config and install steps.
func Generate(o Options) (*Agent, error) {
	u, err := url.Parse(o.ServerURL)
	if err != nil || u.Host == "" {
		return nil, fmt.Errorf("server.public_url %q is not a valid URL; set it in the config file", o.ServerURL)
	}
	if o.Token == "" {
		return nil, fmt.Errorf("no ingest token configured; add one under ingest.tokens")
	}
	host := u.Hostname()
	port := u.Port()
	tls := "Off"
	if u.Scheme == "https" {
		tls = "On"
		if port == "" {
			port = "443"
		}
	} else if port == "" {
		port = "80"
	}

	var b strings.Builder
	a := &Agent{OS: o.OS}
	switch o.OS {
	case "linux":
		a.ConfigPath = "/etc/fluent-bit/fluent-bit.conf"
		b.WriteString("# Signalith agent for Linux, generated by Signalith.\n")
		b.WriteString(section("SERVICE", [][2]string{
			{"Flush", "5"}, {"Log_Level", "info"},
			{"storage.path", "/var/lib/fluent-bit/signalith-buffer"},
			{"storage.sync", "normal"},
		}))
		if o.LinuxSource == "journal" {
			b.WriteString(section("INPUT", [][2]string{
				{"Name", "systemd"}, {"Tag", "linux.journal"},
				{"DB", "/var/lib/fluent-bit/signalith-journal.db"},
				{"Systemd_Filter", "SYSLOG_IDENTIFIER=sshd"},
				{"Systemd_Filter", "SYSLOG_IDENTIFIER=sudo"},
				{"Systemd_Filter", "SYSLOG_IDENTIFIER=su"},
				{"Systemd_Filter", "SYSLOG_IDENTIFIER=useradd"},
				{"Systemd_Filter", "SYSLOG_IDENTIFIER=userdel"},
				{"Systemd_Filter", "SYSLOG_IDENTIFIER=usermod"},
				{"Systemd_Filter", "SYSLOG_IDENTIFIER=gpasswd"},
				{"Read_From_Tail", "On"},
				{"storage.type", "filesystem"},
			}))
		} else {
			b.WriteString(section("INPUT", [][2]string{
				{"Name", "tail"}, {"Tag", "linux.auth"},
				{"Path", "/var/log/auth.log,/var/log/secure"},
				{"DB", "/var/lib/fluent-bit/signalith-auth.db"},
				{"storage.type", "filesystem"},
			}))
		}
		a.Steps = []string{
			"Install Fluent Bit: curl https://raw.githubusercontent.com/fluent/fluent-bit/master/install.sh | sh",
			"Save the configuration below as " + a.ConfigPath,
			"Restart the agent: sudo systemctl enable --now fluent-bit && sudo systemctl restart fluent-bit",
			"Events appear in Search within a minute; check the Health page if they do not.",
		}
	case "windows":
		a.ConfigPath = `C:\Program Files\fluent-bit\conf\fluent-bit.conf`
		channels := "Security"
		if o.Sysmon {
			channels += ",Microsoft-Windows-Sysmon/Operational"
		}
		b.WriteString("# Signalith agent for Windows, generated by Signalith.\n")
		b.WriteString(section("SERVICE", [][2]string{
			{"Flush", "5"}, {"Log_Level", "info"},
			{"storage.path", `C:\ProgramData\fluent-bit\signalith-buffer`},
		}))
		b.WriteString(section("INPUT", [][2]string{
			{"Name", "winevtlog"}, {"Tag", "win.events"},
			{"Channels", channels},
			{"Interval_Sec", "1"},
			{"String_Inserts", "On"},
			{"DB", `C:\ProgramData\fluent-bit\signalith-winevtlog.sqlite`},
			{"storage.type", "filesystem"},
		}))
		a.Steps = []string{
			"Install Fluent Bit for Windows (64-bit installer) from https://docs.fluentbit.io/manual/installation/windows",
			"Save the configuration below as " + a.ConfigPath,
			`Register and start the service in an elevated PowerShell: New-Service fluent-bit -BinaryPathName '"C:\Program Files\fluent-bit\bin\fluent-bit.exe" -c "C:\Program Files\fluent-bit\conf\fluent-bit.conf"' -StartupType Automatic; Start-Service fluent-bit`,
			"Events appear in Search within a minute; check the Health page if they do not.",
		}
		if o.Sysmon {
			a.Steps = append([]string{"Install Sysmon with a config such as SwiftOnSecurity's sysmon-config, so process and network events are recorded"}, a.Steps...)
		}
	default:
		return nil, fmt.Errorf("unknown os %q; use linux or windows", o.OS)
	}
	b.WriteString(section("OUTPUT", [][2]string{
		{"Name", "http"}, {"Match", "*"},
		{"Host", host}, {"Port", port},
		{"URI", "/api/ingest"},
		{"Format", "json"},
		{"Header", "Authorization Bearer " + o.Token},
		{"Header_Tag", "X-Signalith-Tag"},
		{"tls", tls}, {"tls.verify", "On"},
		{"Retry_Limit", "False"},
	}))
	a.Config = b.String()
	return a, nil
}

func section(name string, kv [][2]string) string {
	var b strings.Builder
	b.WriteString("\n[" + name + "]\n")
	for _, p := range kv {
		fmt.Fprintf(&b, "    %-16s %s\n", p[0], p[1])
	}
	return b.String()
}
